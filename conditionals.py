# Conditionals Practice

# Example 1 - Age verification
age = 20

if age >= 18:
    print("Access granted")
else:
    print("Access denied")

# Example 2 - Cutoff mark
score = 210

if score >= 250:
    print("Excellent - Full scholarship")
elif score >= 200:
    print("Admitted - No scholarship")
elif score >= 150:
    print("Waitlisted")
else:
    print("Not admitted")