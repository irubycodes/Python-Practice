a = 20
b = 6

print(a + b)   # addition
print(a - b)   # subtraction
print(a * b)   # multiplication
print(a / b)   # division
print(a // b)  # floor division
print(a % b)   # modulus
print(a ** b)  # exponent

print(10 % 2)   # 0 — even
print(7 % 2)    # 1 — odd

# Unary minus
balance = -1500
print(balance)

# Mixing int and float
print(10 + 2.5)

# ZeroDivisionError - what happens when you divide by zero
print(10 / 0)
